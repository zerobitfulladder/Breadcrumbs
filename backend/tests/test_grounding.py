def test_line_breaks_copied_as_json_escapes_still_match(conn):
    # Seen in a real turn: the model quoted read_pdf's JSON, "\n" and all.
    quote = "The network reaches an error of 1.36 percent on the\\ntest set after sixty epochs"
    assert pdftext.locate_quote(_pdf(conn), quote) is not None
    # A TeX command is not mistaken for one when the quote matches as written.
    assert pdftext.quote_variants(r"rate \nu set") == [r"rate \nu set", "rate  u set"]


def test_a_few_words_identify_nothing(conn):
    assert pdftext.locate_quote(_pdf(conn), "the network") is None


def test_truncated_math_letters_fold_to_plain_ones():
    # U+D459 is what a broken ToUnicode table makes of italic l (U+1D459).
    assert pdftext.fold("patch size 푝") == pdftext.fold("patch size p")


# --- citations ---------------------------------------------------------------
def test_citations_are_checked_and_rewritten(conn):
    text = (
        'The rate is fixed [p. 1](cite:1 "the learning rate is set to 0.03 for every layer"). '
        'It claims more [p. 2](cite:1 "the network reaches perfect accuracy on every benchmark"). '
        'Sparse codes [abs](cite:2 "sparse coding emerges from competition"). '
        'And [x](cite:99 "a paper that does not exist in this library at all").'
    )
    rendered, found = citations.check(conn, text)
    assert [c["status"] for c in found] == [
        citations.VERIFIED, citations.NOT_FOUND, citations.VERIFIED, citations.UNKNOWN_PAPER,
    ]
    assert found[0]["where"] == "pdf" and found[0]["page"] == 1
    assert found[2]["where"] == "abstract"
    assert "cite:" not in rendered and "(citation:1)" in rendered and "(citation:4)" in rendered
    assert citations.summary(found) == {"total": 4, "verified": 2, "failed": 2, "unchecked": 0}
    assert citations.needs_repair(found)


def test_citation_spellings_models_actually_write(conn):
    variants = [
        '[p. 1](cite:1 “why lateral inhibition is needed between hidden units”)',
        '[p. 2](cite:1#p2 "why lateral inhibition is needed between hidden units")',
        "[p. 2](cite:1 'why lateral inhibition is needed between hidden units')",
        '[p. 2](cite:1 "why "lateral inhibition" is needed between hidden units")',
    ]
    for text in variants:
        _, found = citations.check(conn, text)
        assert len(found) == 1 and found[0]["status"] == citations.VERIFIED, text
        assert found[0]["page"] == 2


def test_unverifiable_citations_are_labelled_not_failed(conn):
    _, found = citations.check(
        conn,
        '[a](cite:1) [b](cite:1 "the brain") [c](cite:3 "a quote with no text to check it against")',
    )
    assert [c["status"] for c in found] == [
        citations.NO_QUOTE, citations.TOO_SHORT, citations.NO_SOURCE,
    ]
    assert citations.summary(found)["unchecked"] == 3


def test_prose_without_citations_is_left_alone(conn):
    text = "Feedback alignment uses [a fixed random matrix](https://example.org) instead."
    rendered, found = citations.check(conn, text)
    assert rendered == text and found == []


# --- facts only the server sets -----------------------------------------------
def test_homepage_is_verified_only_from_a_page_this_turn_fetched(conn):
    turn = provenance.Turn(session_id=1, provider="x", model="m")

    async def run(args):
        return await tools.dispatch(conn, None, "set_author_homepage", args, turn=turn)

    # The model claiming verification counts for nothing.
    out = asyncio.run(run({"author_id": 7, "url": "https://example.org/~hinton", "verified": True}))
    assert out["verified"] is False and "not fetched" in out["verification"]

    turn.note_fetch("https://example.org/~hinton", None, "Home page of Someone Else")
    out = asyncio.run(run({"author_id": 7, "url": "https://example.org/~hinton"}))
    assert out["verified"] is False

    turn.note_fetch("http://www.example.org/~hinton/", None, "Geoffrey E. Hinton, University of Toronto")
    out = asyncio.run(run({"author_id": 7, "url": "https://example.org/~hinton"}))
    assert out["verified"] is True


def test_notes_written_by_the_assistant_are_marked(conn):
    conn.execute("INSERT INTO notes(paper_id, body) VALUES (1, 'My own thoughts.')")
    turn = provenance.Turn(session_id=1, provider="x", model="some-model")
    asyncio.run(tools.dispatch(
        conn, None, "add_note",
        {"paper_id": 1, "text": "A summary.\n\nSecond paragraph.", "written_by": "someone"},
        turn=turn,
    ))
    body = conn.execute("SELECT body FROM notes WHERE paper_id = 1").fetchone()["body"]
    assert body.startswith("My own thoughts.\n\n> [!bread] Bread · ")
    assert "some-model" in body and "someone" not in body
    assert "> A summary.\n>\n> Second paragraph." in body


