def test_passages_never_cross_pages_and_keyword_search_finds_them(conn):
    db.set_settings(conn, {"passage_embedder": "off"})   # no model download in tests
    result = passages.index_paper(conn, 1)
    assert result["status"] == "indexed" and result["embedder"] is None
    rows = conn.execute("SELECT page, text FROM passages WHERE paper_id = 1").fetchall()
    assert {r["page"] for r in rows} == {1, 2}

    found = passages.search(conn, "why do hidden units need lateral inhibition?", mode="keyword")
    assert found["results"] and found["results"][0]["page"] == 2
    assert passages.index_paper(conn, 1)["status"] == "current"


