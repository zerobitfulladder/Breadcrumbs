"""The deterministic half of grounding: quote checks, citations, server-set facts.

Everything here runs without a model or a network. A PDF is typeset on the fly
with known text, including the things real papers do to text: a word
hyphenated across a line, a sentence running onto the next page. The base-14
font that typesets it has no Greek or ligature glyphs, so those are tested on
`fold` directly, which is where they are handled.
"""
from __future__ import annotations

import asyncio
import sqlite3
from pathlib import Path

import pytest

from backend import db, passages, pdftext
from backend.ai import citations, provenance, tools

PAGE_ONE = (
    "Learning rules that use only local information are attractive because the "
    "brain has no obvious way to transport error derivatives backwards. We train "
    "each layer with its own objective, which we call the goodness of the layer, "
    "and the learning rate is set to 0.03 for every layer in all experi-\n"
    "ments reported here. The network reaches an error of 1.36 percent on the "
    "test set after sixty epochs of training without data augmentation. Weights "
    "are updated after every mini-batch of one hundred examples, and the "
    "negative data is generated by the network itself rather than taken from a "
    "fixed corpus. The final sentence on this page continues"
)
PAGE_TWO = (
    "onto the second page so that a quote can span the page break. The second "
    "page also discusses why lateral inhibition is needed between hidden units, "
    "and how sparse codes emerge when units compete for the same inputs."
)


def _typeset(path: Path) -> None:
    import pymupdf

    doc = pymupdf.open()
    for text in (PAGE_ONE, PAGE_TWO):
        page = doc.new_page()
        page.insert_textbox(pymupdf.Rect(60, 60, 540, 780), text, fontsize=11)
    doc.save(path)


